const BY_ALPHA2 = new Map(ISO_COUNTRIES.map((country) => [country.a2, country]));
const BY_ALPHA3 = new Map(ISO_COUNTRIES.map((country) => [country.a3, country]));
// Kosovo has no ISO alpha-3. XKX (used here) and XKK both appear in the wild,
// so either one maps back.
const ALPHA3_ALIASES: Record<string, string> = { XKK: "XK" };

/** True for the 249 ISO codes and XK, in any letter case. "UK", "EU" and "ZZ" are not countries. */
export function isCountryCode(code: string | null | undefined): boolean {
  if (typeof code !== "string") return false;
  const trimmed = code.trim();
  return /^[A-Za-z]{2}$/.test(trimmed) && BY_ALPHA2.has(trimmed.toUpperCase());
}

/** The list entry for an alpha-2 code, or null. */
export function isoCountry(code: string | null | undefined): IsoCountry | null {
  if (!isCountryCode(code)) return null;
  return BY_ALPHA2.get(code!.trim().toUpperCase()) ?? null;
}

/** Upper-case alpha-3 for an alpha-2 code ("AE" → "ARE"), or null. Lower-case it for Search Console. */
export function alpha3(code: string): string | null {
  return isoCountry(code)?.a3 ?? null;
}

/** Alpha-2 for an alpha-3 code in any case ("are" → "AE", "gbr" → "GB"), or null for unknown values such as "zzz". */
export function alpha2FromAlpha3(a3: string): string | null {
  if (typeof a3 !== "string") return null;
  const upper = a3.trim().toUpperCase();
  if (!/^[A-Z]{3}$/.test(upper)) return null;
  return BY_ALPHA3.get(upper)?.a2 ?? ALPHA3_ALIASES[upper] ?? null;
}
