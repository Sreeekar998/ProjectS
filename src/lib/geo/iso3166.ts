// ISO 3166-1 country codes: the 249 officially assigned alpha-2 codes plus XK
// (Kosovo, user-assigned but used by Google, CLDR and libphonenumber).
//
// Why a fixed list: the old resolver scanned AA..ZZ through Intl.DisplayNames,
// and CLDR also names deprecated and exceptional codes, so "United Kingdom"
// resolved to UK, "France" to FX and "Serbia" to YU (a .co.uk salon then
// showed a GB/UK "conflict"). `Intl.supportedValuesOf("region")` throws in
// Node 20, so the platform cannot supply the list either.
//
// This is standards reference data, not a market or brand list. `name` is the
// English short name, used only when Intl.DisplayNames is unavailable; display
// names normally come from Intl. Alpha-3 is upper-case here; Google Search
// Console's `country` dimension uses the lower-case form ("are", "gbr").
// `scripts/generate-iso3166.ts` checks the list against libphonenumber and Intl.
//
// Client-safe: no imports.

export interface IsoCountry {
  /** ISO 3166-1 alpha-2, upper-case. */
  a2: string;
  /** ISO 3166-1 alpha-3, upper-case. */
  a3: string;
  /** English short name (fallback when Intl.DisplayNames is missing). */
  name: string;
  /** False only for XK, which ISO has not officially assigned. */
  official: boolean;
}

